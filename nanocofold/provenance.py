"""Content identities for safe inference reuse; no model imports or inference."""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import sys
from functools import lru_cache
from pathlib import Path
from urllib.parse import unquote, urlparse

from .config import resolve_path
from .utils.atomic import check_output

SCHEMA_VERSION = 1
_RUNTIME_ENV_KEYS = ('CUDA_VISIBLE_DEVICES', 'CUDA_DEVICE_ORDER', 'TORCH_HOME', 'XDG_CACHE_HOME',
                     'BOLTZ_CACHE', 'CHAI_DOWNLOADS_DIR', 'RFANTIBODY_ROOT', 'RFANTIBODY_WEIGHTS',
                     'PYTHONPATH', 'PYTHONNOUSERSITE', 'OMP_NUM_THREADS', 'CUBLAS_WORKSPACE_CONFIG',
                     'XLA_PYTHON_CLIENT_PREALLOCATE', 'XLA_PYTHON_CLIENT_MEM_FRACTION', 'TF_FORCE_UNIFIED_MEMORY',
                     'JAX_COMPILATION_CACHE_DIR', 'JAX_PLATFORMS', 'XLA_FLAGS', 'HF_HOME', 'HF_HUB_OFFLINE', 'HF_DATASETS_OFFLINE')


@lru_cache(maxsize=4096)
def _cached_digest(path: str, size: int, mtime_ns: int, ctime_ns: int, inode: int) -> str:
    digest = hashlib.sha256()
    with Path(path).open('rb') as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def file_digest(path: Path | str) -> str:
    path = Path(path).resolve()
    info = path.stat()
    return _cached_digest(str(path), info.st_size, info.st_mtime_ns, info.st_ctime_ns, info.st_ino)


@lru_cache(maxsize=8)
def _directory_digest(identities: tuple) -> str:
    digest = hashlib.sha256()
    # Read in inode order to reduce seeks on filesystems that allocate in
    # extraction order; identity order stays lexical.
    hashes = {relative: verified or _cached_digest(path, size, mtime, ctime, inode)
              for relative, path, size, mtime, ctime, inode, verified in sorted(identities, key=lambda row: row[5])}
    for relative, path, size, mtime, ctime, inode, verified in identities:
        digest.update(relative.encode())
        digest.update(b'\0')
        digest.update(hashes[relative].encode())
        digest.update(b'\n')
    return digest.hexdigest()


@lru_cache(maxsize=8)
def _verified_index(path: str, size: int, mtime: int, ctime: int, inode: int):
    try:
        data = json.loads(Path(path).read_text())
        files = data.get('files', {})
        if data.get('schema_version') == 1 and isinstance(files, dict):
            return files, _cached_digest(path, size, mtime, ctime, inode)
    except (OSError, ValueError, TypeError):
        pass
    return {}, None


def directory_identity(root: Path | str) -> dict:
    """Compact content identity; only metadata is rescanned between candidates.

    Contents enter the identity, so same-size changes and restored mtimes are
    detected through ctime. Additions, deletion and renaming change the key.
    The directory cache avoids rehashing thousands of unchanged molecule files.
    """
    root = Path(root).resolve()
    identities = []
    verified, index_sha = {}, None
    index = root.parent / '.nanocofold-molecules.json'
    if root.name == 'mols' and index.is_file():
        info = index.stat()
        verified, index_sha = _verified_index(str(index), info.st_size, info.st_mtime_ns, info.st_ctime_ns, info.st_ino)
    for path in sorted(root.rglob('*')) if root.is_dir() else []:
        if path.is_file():
            info = path.stat()
            relative = str(path.relative_to(root))
            signature = [info.st_size, info.st_mtime_ns, info.st_ctime_ns, info.st_ino]
            row = verified.get(relative)
            known = row[-1] if isinstance(row, list) and len(row) == 5 and row[:4] == signature and isinstance(row[-1], str) and len(row[-1]) == 64 and all(c in '0123456789abcdef' for c in row[-1]) else None
            identities.append((relative, str(path.resolve()), *signature, known))
    result = {'path': str(root), 'file_count': len(identities), 'sha256': _directory_digest(tuple(identities))}
    if index_sha:
        result['index_sha256'] = index_sha
    return result


def fingerprint(payload: dict) -> str:
    return hashlib.sha256(json.dumps(payload, sort_keys=True, default=str, separators=(',', ':')).encode()).hexdigest()


def application_identity(root: Path | None = None) -> str:
    """Identity of installed application code/config, independent of its path.

    A package version or cloud_agent.py hash alone cannot detect adapter and
    report changes. Ignore generated bytecode; detect edits and added files.
    """
    root = root or Path(__file__).resolve().parent
    return fingerprint({str(p.relative_to(root)): file_digest(p)
                        for p in sorted(root.rglob("*")) if p.is_file()
                        and "__pycache__" not in p.parts and p.suffix not in {".pyc", ".pyo"}})


def output_manifest(root: Path) -> dict[str, str]:
    """All engine artifacts, not just parseable first structures, must be intact."""
    return {str(path.relative_to(root)): file_digest(path) for path in sorted(root.rglob('*')) if path.is_file()}


def outputs_match(root: Path, manifest) -> bool:
    return isinstance(manifest, dict) and bool(manifest) and manifest == output_manifest(root)


def archive_existing(paths: list[Path], root: Path) -> Path | None:
    """Preserve each unique superseded artifact set once, under its content identity."""
    root = root.resolve()
    present = [Path(path) for path in paths if path.exists()]
    if not present:
        return None

    def identity(entries):
        manifest = {}
        for path in entries:
            if path.is_symlink() or not path.resolve().is_relative_to(root):
                raise ValueError("보존할 산출물은 실행 내부의 실제 파일이어야 합니다.")
            if path.name in manifest:
                raise ValueError("보존할 산출물 이름이 중복됩니다.")
            if path.is_dir():
                if any(item.is_symlink() for item in path.rglob("*")):
                    raise ValueError("링크를 포함한 산출물은 자동 보존할 수 없습니다.")
                manifest[path.name] = {"kind": "directory", "files": output_manifest(path)}
            else:
                manifest[path.name] = {"kind": "file", "sha256": file_digest(path)}
        return manifest

    manifest = identity(present)
    destination = root / '.history' / fingerprint(manifest)
    check_output(destination, root)
    if destination.exists():
        if destination.is_symlink() or identity(list(destination.iterdir())) != manifest:
            raise ValueError("기존 보존 사본의 해시가 다릅니다. 원본을 유지했습니다.")
        # Only remove redundant active copies after verifying the preserved set.
        # Distinct scientific outputs and all existing history remain immutable.
        if identity(present) != manifest:
            raise ValueError("보존 중 산출물이 변경되었습니다.")
        for path in present:
            if path.is_dir():
                shutil.rmtree(path)
            else:
                path.unlink()
        return destination
    destination.mkdir(parents=True)
    for path in present:
        shutil.move(str(path), str(destination / path.name))
    return destination


def runtime_identity(cfg: dict, engine: str, *, env=None, argv=None, env_vars=None) -> dict:
    """Engine source, installed metadata, local weights, Python and effective env.

    Stat-keyed hashing avoids re-reading gigabyte weights for each candidate;
    altered content/metadata invalidates that optimization. No torch import/CUDA
    initialization occurs here.
    """
    from . import diagnostics
    if env is None:
        env = resolve_path(cfg, diagnostics._engine_spec(cfg, engine).get('env'))
    env = Path(env) if env else None
    overrides = dict(diagnostics._engine_extra_env(cfg, engine))
    overrides.update(env_vars or {})
    effective_env = {key: os.environ.get(key) for key in _RUNTIME_ENV_KEYS}
    for key, value in overrides.items():
        effective_env[str(key)] = str(value) if value is not None else None
    sources = []
    packages = {'opendde': ['opendde', 'runner'], 'chai1': ['chai_lab'], 'boltz2': ['boltz'], 'rfantibody': ['rfantibody'],
                'esm': ['esm'], 'antifold': ['antifold'], 'colabfold': ['colabfold', 'alphafold']}.get(engine, [engine])
    sites = diagnostics._site_packages_roots(env) if env else [Path(p) for p in sys.path if 'site-packages' in p]
    for site in sites:
        for package in packages:
            source = site / package
            if source.is_dir():
                sources.extend(source.rglob('*.py'))
                if engine == 'boltzgen':
                    sources.extend(source.rglob('*.yaml'))
            # Distribution metadata records version and direct_url VCS identity.
            for dist in site.glob(package.replace('_', '-') + '-*.dist-info'):
                sources.extend(p for p in (dist / 'METADATA', dist / 'direct_url.json') if p.is_file())
            for dist in site.glob(package + '-*.dist-info'):
                sources.extend(p for p in (dist / 'METADATA', dist / 'direct_url.json') if p.is_file())
        # Numeric runtime versions matter even if the engine source is unchanged.
        dependencies = ['torch', 'numpy'] + (['dgl'] if engine == 'rfantibody' else [])
        if engine in {'esm', 'antifold'}:
            dependencies.extend(['fair_esm', 'biotite'])
        if engine == 'colabfold':
            dependencies.extend(['jax', 'jaxlib', 'jax_cuda13_plugin', 'jax_cuda13_pjrt', 'dm_haiku'])
        for dependency in dependencies:
            for dist in site.glob(dependency + '-*.dist-info'):
                sources.extend(p for p in (dist / 'METADATA', dist / 'direct_url.json') if p.is_file())
    # Editable installs may execute source outside site-packages. Include that
    # source tree rather than trusting a version string/direct_url alone.
    for direct_url in [p for p in sources if p.name == 'direct_url.json']:
        try:
            payload = json.loads(direct_url.read_text())
            parsed = urlparse(payload.get('url', ''))
            if payload.get('dir_info', {}).get('editable') and parsed.scheme == 'file':
                checkout = Path(unquote(parsed.path))
                for package in packages:
                    for source in (checkout / package, checkout / 'src' / package):
                        if source.is_dir():
                            sources.extend(source.rglob('*.py'))
                            if engine == 'boltzgen':
                                sources.extend(source.rglob('*.yaml'))
        except (OSError, ValueError, TypeError):
            pass  # The metadata bytes still enter the fingerprint.
    if engine == 'rfantibody':
        source_root = overrides.get('RFANTIBODY_ROOT') or os.environ.get('RFANTIBODY_ROOT')
        if source_root:
            source = Path(source_root)
            for folder in ('src', 'include'):
                if (source / folder).is_dir():
                    sources.extend((source / folder).rglob('*.py'))
    # Application adapters and the actual launched entrypoint are identities too.
    package_root = Path(__file__).resolve().parent
    sources.extend([package_root / 'screen.py', package_root / 'design_rfantibody.py', package_root / 'colabfold.py',
                    package_root / 'design_boltzgen.py', package_root / 'design_routing.py'])
    sources.extend((package_root / 'scripts').glob('*.py'))
    sources.extend(Path(a) for i, a in enumerate(argv or []) if (i == 0 or str(a).endswith('.py')) and Path(str(a)).is_file())
    weights = diagnostics._engine_weight_manifest(cfg, engine, env)
    support = {'molecules': directory_identity(diagnostics._boltz_cache_path(cfg) / 'mols')} if engine == 'boltz2' else {}
    python = diagnostics._env_python(env)
    return {'schema_version': SCHEMA_VERSION, 'engine': engine, 'env': str(env) if env else None,
            'python': {'path': str(python) if python else None,
                       'sha256': file_digest(python) if python and python.is_file() else None},
            'environment': effective_env,
            'source': {str(p.resolve()): file_digest(p) for p in sorted(set(sources)) if p.is_file()},
            'weights': weights, 'support': support}
