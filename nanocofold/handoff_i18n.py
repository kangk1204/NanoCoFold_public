def _compile_template(template: str) -> re.Pattern[str]:
    parts = []
    for literal, field, _format_spec, _conversion in Formatter().parse(template):
        parts.append(re.escape(literal))
        if field is not None:
            parts.append('(.*)')
    return re.compile(''.join(parts), re.DOTALL)


_MESSAGES: dict[str, tuple] = {}
for _codes, _source, _ko, _en in MESSAGE_CATALOG:
    for _code in _codes:
        _MESSAGES[_code] = (*_MESSAGES.get(_code, ()), (_compile_template(_source), _ko, _en))
_SPECIFICITY = tuple((_compile_template(source), ko, en) for source, ko, en in SPECIFICITY_CATALOG)


def _translate(message: str, language: str, catalog: tuple) -> str:
    for pattern, ko, en in catalog:
        match = pattern.fullmatch(message)
        if match:
            return (ko if language == 'ko' else en).format(*match.groups())
    return message


def localize_handoff(result: dict[str, Any], language: str = 'en') -> dict[str, Any]:
    """Return a localized CLI view without changing validation or its input."""
    if language not in {'ko', 'en'}:
        raise ValueError('language must be ko or en')
    localized = dict(result)
    prefix = 'specificity target definition is invalid: '
    for category in ('errors', 'warnings'):
        diagnostics = []
        for item in result.get(category, []):
            diagnostic = dict(item)
            message = diagnostic.get('message', '')
            if diagnostic.get('code') == 'invalid_specificity_definition' and message.startswith(prefix):
                nested = _translate(message[len(prefix):], language, _SPECIFICITY)
                message = prefix + nested
            diagnostic['message'] = _translate(message, language, _MESSAGES.get(diagnostic.get('code'), ()))
            diagnostics.append(diagnostic)
        localized[category] = diagnostics
    return localized
