/* Explicit presentation bindings; no DOM observer, input rewriting, or API mutation. */
globalThis.I18N = (() => {
  let language = 'en';
  const storageKey = 'nanocofold.language';
  const bindings = new Set();
  const bindingIndex = new WeakMap();
  const cleanup = new FinalizationRegistry(reference => bindings.delete(reference));
  const tag = Symbol('localized presentation');
  const normalize = s => s.replace(/\s+/g, ' ').trim();
  const normalized = new Map(Object.entries(NCF_TRANSLATIONS).map(([k,v])=>[normalize(k),v]));
  const patterns = Object.entries(NCF_TRANSLATIONS).filter(([k])=>/\{\d+\}/.test(k)).map(([ko,en])=>{
    const keys=[];
    const escaped=ko.split(/(\{\d+\})/).map(part=>{
      if(/^\{\d+\}$/.test(part)){keys.push(part);return '([\\s\\S]*?)';}
      return part.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
    }).join('');
    return {pattern:new RegExp('^'+escaped+'$'),keys,en};
  });
  function translate(raw) {
    if(typeof raw!=='string')return raw==null?'':String(raw);
    if(Object.hasOwn(NCF_TRANSLATIONS,raw))return NCF_TRANSLATIONS[raw];
    if(normalized.has(normalize(raw)))return normalized.get(normalize(raw));
    for(const {pattern,keys,en} of patterns){
      const match=pattern.exec(raw);if(!match)continue;
      const values=new Map(keys.map((k,i)=>[k,match[i+1]]));
      // One replacement pass: data containing {0} is not reinterpreted as a placeholder.
      return en.replace(/\{\d+\}/g,key=>values.get(key)??key);
    }
    return raw;
  }
  const message = (ko,en) => Object.freeze({[tag]:true,ko:String(ko??''),en:String(en??'')});
  const at = (value,lang) => value?.[tag] ? value[lang] : String(value??'');
  const korean = raw => Object.hasOwn(NCF_LEGACY_TERMS,raw) ? NCF_LEGACY_TERMS[raw] : raw;
  const term = raw => raw?.[tag] ? raw : message(korean(raw),translate(raw));
  function format(key,args){
    const interpolate=(template,lang)=>template.replace(/\{(\d+)\}/g,(_,i)=>at(args[Number(i)],lang));
    return message(interpolate(korean(key),'ko'),interpolate(NCF_TRANSLATIONS[key]||key,'en'));
  }
  const concat = values => message(values.map(v=>at(v,'ko')).join(''),values.map(v=>at(v,'en')).join(''));
  function bind(node,field,value){
    if(!node)return;
    if(field==='textContent'){
      bindingIndex.get(node)?.delete(field);
      // Bind the created text node, not its parent. Later append/replaceChildren
      // must retain controls and must not revive text that was already replaced.
      node.textContent=at(value,language);
      if(!value?.[tag])return;
      node=node.nodeType===1 ? node.firstChild : node;
      if(!node)return;
    } else {
      node.setAttribute(field,at(value,language));
      if(!value?.[tag]){bindingIndex.get(node)?.delete(field);return;}
    }
    if(!bindingIndex.has(node)){
      bindingIndex.set(node,new Map());const reference=new WeakRef(node);
      bindings.add(reference);cleanup.register(node,reference);
    }
    bindingIndex.get(node).set(field,value);
  }
  function apply(){
    for(const reference of bindings){
      const node=reference.deref();
      if(!node||node.isConnected===false){bindings.delete(reference);continue;}
      const fields=bindingIndex.get(node);
      for(const [field,value]of fields){
        if(field==='textContent')node.textContent=at(value,language);
        else node.setAttribute(field,at(value,language));
      }
    }
    if(typeof document!=='undefined'){
      document.documentElement.lang=language;
      const select=document.getElementById('language-select');if(select)select.value=language;
      const label=document.querySelector('[for="language-select"]');if(label)label.textContent=language==='ko'?'언어':'Language';
    }
  }
  function setLanguage(next,{persist=true}={}){
    if(!['en','ko'].includes(next))return;
    language=next;apply();
    if(persist){try{localStorage.setItem(storageKey,language);}catch{/* Storage may be blocked in standalone reports. */}}
    if(typeof document!=='undefined')document.dispatchEvent(new CustomEvent('nanocofold:language',{detail:{language}}));
  }
  function init(){
    let saved;try{saved=localStorage.getItem(storageKey);}catch{}
    const query=new URLSearchParams(location.search).get('lang');
    language=['en','ko'].includes(query)?query:['en','ko'].includes(saved)?saved:'en';
    // Bind only initial UI nodes. Later data is handled by explicit call sites.
    const walk=document.createTreeWalker(document.documentElement,NodeFilter.SHOW_TEXT);
    const nodes=[];while(walk.nextNode())nodes.push(walk.currentNode);
    for(const node of nodes){
      if(node.parentElement?.closest('script,style,textarea,pre,code,[data-i18n-ignore]'))continue;
      if(/[가-힣]/.test(node.textContent))bind(node,'textContent',term(node.textContent));
    }
    for(const node of document.querySelectorAll('[placeholder],[aria-label],[title]')){
      if(node.closest('[data-i18n-ignore]'))continue;
      for(const field of ['placeholder','aria-label','title']){
        const value=node.getAttribute(field);if(value&&/[가-힣]/.test(value))bind(node,field,term(value));
      }
    }
    document.getElementById('language-select')?.addEventListener('change',event=>setLanguage(event.target.value));
    apply();
  }
  return Object.freeze({init,setLanguage,term,format,concat,text:(node,value)=>bind(node,'textContent',value),
    attribute:(node,name,value)=>bind(node,name,value),attributeValue:(node,name)=>bindingIndex.get(node)?.get(name) ?? node.getAttribute(name),value:value=>at(value,language),get language(){return language;}});
})();
